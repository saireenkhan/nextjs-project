"use client";

import React, { useState, useEffect } from "react";
import { API_BASE_URL } from "@/utils/api";

const AddClassForm = ({ fields, onSubmit }) => {
  const allowedInputTypes = [
    "text",
    "number",
    "email",
    "time",
    "password",
    "date",
    "tel",
    "url",
    "file",
  ];

  const [formData, setFormData] = useState({});

  useEffect(() => {
    const initializeForm = async () => {
      const initialValues = {};
      
      if (Array.isArray(fields)) {
        for (const element of fields) {
          if (element.type === "row" && Array.isArray(element.fields)) {
            for (const subField of element.fields) {
              if (subField.type !== "file" && isAutoGeneratedField(subField.label)) {
                initialValues[subField.label] = await fetchAutoId(subField.label);
              }
            }
          } else if (element.label && element.type !== "file" && isAutoGeneratedField(element.label)) {
            initialValues[element.label] = await fetchAutoId(element.label);
          }
        }
      }
      setFormData(initialValues);
    };

    initializeForm();
  }, [fields]);

  const fetchAutoId = async (label) => {
    const lower = label.toLowerCase();
    let endpoint = "";
    let fallbackPrefix = "ID";

    if (lower.includes("fund")) { endpoint = "funds"; fallbackPrefix = "FND"; }
    else if (lower.includes("staff")) { endpoint = "staff"; fallbackPrefix = "STF"; }
    else if (lower.includes("event")) { endpoint = "events-khateeb"; fallbackPrefix = "EVT"; }
    else if (lower.includes("transaction")) { endpoint = "bank-cash"; fallbackPrefix = "TRX"; }
    else if (lower.includes("receipt")) { endpoint = "expenses"; fallbackPrefix = "EXP"; }
    else if (lower.includes("rating")) { endpoint = "ratings"; fallbackPrefix = "RAT"; }

    if (!endpoint) return `${fallbackPrefix}-${Math.floor(1000 + Math.random() * 9000)}`;

    try {
      const res = await fetch(`${API_BASE_URL}/${endpoint}/next-id`);
      const data = await res.json();
      if (data.success && data.nextId) return data.nextId;
    } catch (e) {
      // Fallback client-side code if backend route is unavailable
    }
    return `${fallbackPrefix}-${Math.floor(1000 + Math.random() * 9000)}`;
  };

  const isAutoGeneratedField = (label = "") => {
    const lower = label.toLowerCase().trim();
    return lower.endsWith("id") || lower === "id" || lower.includes("code") || lower.includes("receipt");
  };

  // Helper to calculate rating average automatically
  const calculateAndUpdateAverage = (updatedData) => {
    const ratingKeys = [
      "Knowledge",
      "Akhlaq / Adab",
      "Punctuality",
      "Khutba / Azan Quality",
      "Community Behavior"
    ];

    let sum = 0;
    let count = 0;

    ratingKeys.forEach((key) => {
      const val = parseFloat(updatedData[key]);
      if (!isNaN(val) && val > 0) {
        sum += val;
        count += 1;
      }
    });

    if (count > 0) {
      updatedData["Average Rating"] = (sum / count).toFixed(1); // Format to 1 decimal place e.g., "4.2"
    } else {
      updatedData["Average Rating"] = "";
    }

    return updatedData;
  };

  const handleChange = (label, value, isFile = false) => {
    setFormData((prev) => {
      const nextData = {
        ...prev,
        [label]: isFile ? value : value,
      };
      return calculateAndUpdateAverage(nextData);
    });
  };

  const handleFormSubmit = (e) => {
    e.preventDefault();
    if (onSubmit) onSubmit(formData);
  };

  return (
    <form onSubmit={handleFormSubmit}>
      {Array.isArray(fields) &&
        fields.map((element, index) => {
          // ROWS
          if (element.type === "row" && Array.isArray(element.fields)) {
            return (
              <div className="form-row donation-row" key={`row-${index}`}>
                {element.fields.map((subField, subIndex) => {
                  const inputType = allowedInputTypes.includes(subField.type)
                    ? subField.type
                    : "text";

                  const isFile = inputType === "file";
                  const isAutoId = !isFile && isAutoGeneratedField(subField.label);
                  const isAverageField = subField.label.toLowerCase().includes("average rating");

                  return (
                    <div className="form-group" key={`field-${subIndex}`}>
                      <label>
                        {subField.required && <span className="required-star">*</span>}
                        {subField.label}
                      </label>

                      {subField.type === "select" ? (
                        <select
                          value={formData[subField.label] || ""}
                          onChange={(e) => handleChange(subField.label, e.target.value)}
                        >
                          <option value="">Select {subField.label}</option>
                          {subField.options?.map((opt, idx) => (
                            <option key={idx} value={opt}>
                              {opt}
                            </option>
                          ))}
                        </select>
                      ) : isFile ? (
                        <input
                          type="file"
                          onChange={(e) => handleChange(subField.label, e.target.files[0], true)}
                        />
                      ) : (
                        <input
                          type={inputType}
                          placeholder={subField.placeholder || ""}
                          value={formData[subField.label] || ""}
                          disabled={isAutoId || isAverageField}
                          style={
                            isAutoId || isAverageField
                              ? { backgroundColor: "#f3f4f6", cursor: "not-allowed", fontWeight: "600" }
                              : {}
                          }
                          onChange={(e) => handleChange(subField.label, e.target.value)}
                        />
                      )}
                    </div>
                  );
                })}
              </div>
            );
          }

          // SINGLE FIELDS & TEXTAREAS
          const fieldType = allowedInputTypes.includes(element.type)
            ? element.type
            : "text";

          const isFile = fieldType === "file";
          const isAutoId = !isFile && isAutoGeneratedField(element.label);
          const isAverageField = element.label.toLowerCase().includes("average rating");

          return (
            <div className="form-group full-width" key={`single-${index}`}>
              <label>
                {element.required && <span className="required-star">*</span>}
                {element.label}
              </label>

              {element.type === "select" ? (
                <select
                  value={formData[element.label] || ""}
                  onChange={(e) => handleChange(element.label, e.target.value)}
                >
                  <option value="">Select {element.label}</option>
                  {element.options?.map((opt, idx) => (
                    <option key={idx} value={opt}>
                      {opt}
                    </option>
                  ))}
                </select>
              ) : isFile ? (
                <input
                  type="file"
                  onChange={(e) => handleChange(element.label, e.target.files[0], true)}
                />
              ) : (
                <input
                  type={fieldType}
                  placeholder={element.placeholder || ""}
                  value={formData[element.label] || ""}
                  disabled={isAutoId || isAverageField}
                  style={
                    isAutoId || isAverageField
                      ? { backgroundColor: "#f3f4f6", cursor: "not-allowed", fontWeight: "600" }
                      : {}
                  }
                  onChange={(e) => handleChange(element.label, e.target.value)}
                />
              )}
            </div>
          );
        })}

      <div className="donation-buttons">
        <button type="submit" className="btn-save">
          Submit Record
        </button>
      </div>
    </form>
  );
};

export default AddClassForm;