"use client";

import React, { useState, useEffect } from "react";
import { FileText, Search, Plus } from "lucide-react";

import Sidebar2 from "@/components/Sidebar";
import Header from "@/components/Header";
import PageHeader from "@/components/PageHeader";
import DataTable from "@/components/DataTable";
import AddClassForm from "@/components/AddClassForm";
import ModalWrapper from "@/components/ModalWrapper";

import { ReportsFormSchema } from "@/Data/Data";
import { fetchReports, createReport } from "@/utils/api";

import "../../css/Pages.css";

const Reportss = () => {
  const [reportsList, setReportsList] = useState([]);
  const [loading, setLoading] = useState(true);
  const [isModalOpen, setIsModalOpen] = useState(false);

  // Search & Filter States
  const [searchQuery, setSearchQuery] = useState("");
  const [selectedTypeFilter, setSelectedTypeFilter] = useState("All");
  const [selectedCategoryFilter, setSelectedCategoryFilter] = useState("All");

  useEffect(() => {
    loadReports();
  }, []);

  const loadReports = async () => {
    setLoading(true);
    const data = await fetchReports();
    setReportsList(Array.isArray(data) ? data : []);
    setLoading(false);
  };

  const handleAddReport = async (formData) => {
    console.log("Raw Report Form Data Received:", formData);

    const payload = {
      reportType: formData?.reportType || formData?.["Report Type"] || "General Financial Statement",
      fromDate: formData?.fromDate || formData?.["From Date"] || "",
      toDate: formData?.toDate || formData?.["To Date"] || "",
      fundCategory: formData?.fundCategory || formData?.["Fund Category"] || "Masjid general fund",
      format: formData?.format || formData?.["Format"] || "PDF",
      generatedBy: formData?.generatedBy || formData?.["Generated By"] || "Admin"
    };

    console.log("Processed Report Payload Sent to Database:", payload);

    const result = await createReport(payload);
    if (result && result.success) {
      alert("Report generated successfully!");
      setIsModalOpen(false); // Close modal on success
      loadReports();
    } else {
      alert("Error generating report: " + (result?.error || "Unknown error"));
    }
  };

  const handleDownloadPdf = (id) => {
    window.open(`http://localhost:5002/api/reports/${id}/pdf`, "_blank");
  };

  // Filtering and Searching Logic
  const filteredReports = reportsList.filter((item) => {
    const matchesSearch = 
      !searchQuery || 
      (item.reportType && item.reportType.toLowerCase().includes(searchQuery.toLowerCase())) ||
      (item.generatedBy && item.generatedBy.toLowerCase().includes(searchQuery.toLowerCase()));

    const matchesType = 
      selectedTypeFilter === "All" || 
      (item.reportType && item.reportType.toLowerCase() === selectedTypeFilter.toLowerCase());

    const matchesCategory = 
      selectedCategoryFilter === "All" || 
      (item.fundCategory && item.fundCategory.toLowerCase() === selectedCategoryFilter.toLowerCase());

    return matchesSearch && matchesType && matchesCategory;
  });

  return (
    <div className="campus-layout">
      <Sidebar2 />

      <div className="main-content">
        <Header />

        <div className="page-container">
          {/* Header Row with Right-End Trigger Button */}
  <div
             style={{
               display: "flex",
               alignItems: "center",
               width: "100%",
               marginBottom: "16px",
               gap: "20px",
             }}
           >
             <div style={{ flex: 1, minWidth: 0 }}>
               <PageHeader title="Reports and Statements" />
             </div>
           
             <button className="btn-add-staff">
               <Plus size={18} />
               Generate Report
             </button>
             </div>

          <div className="donation-info-box">
            Generate and export financial and operational reports.
          </div>

          {/* ================= SEARCH & FILTERS ROW ================= */}
          <div className="filters-row">
            <div className="search-box" style={{ position: 'relative' }}>
              <Search size={18} style={{ position: 'absolute', left: '14px', top: '12px', color: '#555' }} />
              <input 
                type="text" 
                placeholder="Search resources..." 
                value={searchQuery}
                onChange={(e) => setSearchQuery(e.target.value)}
                style={{ paddingLeft: '40px' }} 
              />
            </div>

            {/* Report Type Filter */}
            <select 
              className="filter-select"
              value={selectedTypeFilter}
              onChange={(e) => setSelectedTypeFilter(e.target.value)}
            >
              <option value="All">All Report Types</option>
              <option value="General Financial Statement">General Financial Statement</option>
              <option value="Donation Summary">Donation Summary</option>
              <option value="Expense Report">Expense Report</option>
              <option value="Staff Salary Ledger">Staff Salary Ledger</option>
            </select>

            {/* Fund Category Filter */}
            <select 
              className="filter-select"
              value={selectedCategoryFilter}
              onChange={(e) => setSelectedCategoryFilter(e.target.value)}
            >
              <option value="All">All Fund Categories</option>
              <option value="Masjid general fund">Masjid general fund</option>
              <option value="Zakat fund">Zakat fund</option>
              <option value="Construction fund">Construction fund</option>
              <option value="Madrasa fund">Madrasa fund</option>
            </select>
          </div>

          <DataTable
            headers={[
              "#",
              "Report Type",
              "From Date",
              "To Date",
              "Fund Category",
              "Format",
              "Generated By",
              "Action",
            ]}
          >
            {loading ? (
              <tr>
                <td colSpan="8" style={{ textAlign: "center", padding: "20px" }}>
                  Loading database records...
                </td>
              </tr>
            ) : filteredReports.length === 0 ? (
              <tr>
                <td colSpan="8" style={{ textAlign: "center", padding: "20px" }}>
                  No matching reports found in database.
                </td>
              </tr>
            ) : (
              filteredReports.map((item, index) => (
                <tr key={item._id || index}>
                  <td>{item.id || index + 1}</td>

                  <td>
                    <strong>{item.reportType}</strong>
                  </td>

                  <td>{item.fromDate}</td>

                  <td>{item.toDate}</td>

                  <td>{item.fundCategory}</td>

                  <td>{item.format}</td>

                  <td>{item.generatedBy}</td>

                  <td>
                    <button
                      type="button"
                      onClick={() => handleDownloadPdf(item._id)}
                      style={{
                        display: "inline-flex",
                        alignItems: "center",
                        gap: "6px",
                        background: "#f3f4f6",
                        border: "1px solid #d1d5db",
                        padding: "6px 12px",
                        borderRadius: "6px",
                        cursor: "pointer",
                        color: "#dc2626",
                        fontWeight: "600",
                      }}
                    >
                      <FileText size={14} />
                      Export
                    </button>
                  </td>
                </tr>
              ))
            )}
          </DataTable>
        </div>
      </div>

      {/* Modal Wrapper Containing Form */}
      <ModalWrapper 
        isOpen={isModalOpen} 
        onClose={() => setIsModalOpen(false)} 
        title="Generate New Report"
      >
        <AddClassForm fields={ReportsFormSchema} onSubmit={handleAddReport} />
      </ModalWrapper>
    </div>
  );
};

export default Reportss;