"use client";

import React, { useState, useEffect } from "react";
import { FileText, Search, Plus } from "lucide-react";

import SidebarCommittee from "../../../components/SidebarCommittee";
import Header from "@/components/Header";
import PageHeader from "@/components/PageHeader";
import DataTable from "@/components/DataTable";
import AddClassForm from "@/components/AddClassForm";
import ModalWrapper from "@/components/ModalWrapper";

import { ReportsFormSchema } from "@/Data/DataCommittee";
import { fetchReports, createReport } from "@/utils/api";

import "../../css/Pages.css";

const Reportss2 = () => {
  const [reportsList, setReportsList] = useState([]);
  const [loading, setLoading] = useState(true);
  const [isModalOpen, setIsModalOpen] = useState(false);

  // Search & Type Filter States
  const [searchQuery, setSearchQuery] = useState("");
  const [selectedTypeFilter, setSelectedTypeFilter] = useState("All");

  useEffect(() => {
    loadReports();
  }, []);

  const loadReports = async () => {
    setLoading(true);
    const data = await fetchReports();
    setReportsList(Array.isArray(data) ? data : []);
    setLoading(false);
  };

 const handleAddReport = async (formData) => {
    const today = new Date().toISOString().split("T")[0];

    const payload = {
      reportId: formData?.reportId || formData?.["Report ID"] || `REP-${Math.floor(1000 + Math.random() * 9000)}`,
      reportType: formData?.reportType || formData?.["Report Type"] || "Summary",
      fundCategory: formData?.fundCategory || formData?.["Fund Category"] || "General",
      exportFormat: formData?.exportFormat || formData?.["Format"] || "PDF",
      generatedBy: formData?.generatedBy || formData?.["Generated By"] || "Committee Member",
      generatedDate: formData?.generatedDate || formData?.["Generated Date"] || today,
      
      // Added required date fields with safe fallbacks
      fromDate: formData?.fromDate || formData?.["From Date"] || today,
      toDate: formData?.toDate || formData?.["To Date"] || today,
    };

    const result = await createReport(payload);
    if (result && result.success) {
      alert("Report generated successfully!");
      setIsModalOpen(false);
      loadReports();
    } else {
      alert("Error saving report: " + (result?.error || "Unknown error"));
    }
  };
  const handleExportReport = (id) => {
    window.open(`http://localhost:5000/api/reports/${id}/download`, "_blank");
  };

  // Filter & Search Logic
  const filteredReports = reportsList.filter((item) => {
    const matchesSearch = 
      !searchQuery || 
      (item.reportId && item.reportId.toLowerCase().includes(searchQuery.toLowerCase())) ||
      (item.fundCategory && item.fundCategory.toLowerCase().includes(searchQuery.toLowerCase())) ||
      (item.generatedBy && item.generatedBy.toLowerCase().includes(searchQuery.toLowerCase()));

    const matchesType = 
      selectedTypeFilter === "All" || 
      (item.reportType && item.reportType.toLowerCase() === selectedTypeFilter.toLowerCase());

    return matchesSearch && matchesType;
  });

  return (
    <div className="campus-layout">
      <SidebarCommittee />

      <div className="main-content">
        <Header />

        <div className="page-container">
          {/* Header Row with Trigger Button */}
         <div
  style={{
    display: "flex",
    alignItems: "center",
    width: "100%",
    marginBottom: "16px",
    gap: "20px",
  }}
>
  <div style={{ flex: 1, minWidth: 0 }}>
    <PageHeader title="Reports & Statements" />
  </div>

  <button className="btn-add-staff">
    <Plus size={18} />
    Generate Reports
  </button>
</div>

          <div className="donation-info-box">
            Monthly/yearly income-expense reports, category-wise, donor-wise and date-wise reports with PDF/Excel export.
          </div>

          {/* Search & Filters */}
          <div className="filters-row">
            <div className="search-box" style={{ position: 'relative' }}>
              <Search size={18} style={{ position: 'absolute', left: '14px', top: '12px', color: '#555' }} />
              <input 
                type="text" 
                placeholder="Search Report ID, Category or Author..." 
                value={searchQuery}
                onChange={(e) => setSearchQuery(e.target.value)}
                style={{ paddingLeft: '40px' }} 
              />
            </div>

            <select 
              className="filter-select"
              value={selectedTypeFilter}
              onChange={(e) => setSelectedTypeFilter(e.target.value)}
            >
              <option value="All">All Types</option>
              <option value="Monthly">Monthly</option>
              <option value="Yearly">Yearly</option>
              <option value="Category-wise">Category-wise</option>
              <option value="Donor-wise">Donor-wise</option>
            </select>
          </div>

          <DataTable
            headers={[
              "#",
              "Report ID",
              "Report Type",
              "Fund Category",
              "Format",
              "Generated By",
              "Generated Date",
              "Action",
            ]}
          >
            {loading ? (
              <tr>
                <td colSpan="8" style={{ textAlign: "center", padding: "20px" }}>
                  Loading database records...
                </td>
              </tr>
            ) : filteredReports.length === 0 ? (
              <tr>
                <td colSpan="8" style={{ textAlign: "center", padding: "20px" }}>
                  No report records found.
                </td>
              </tr>
            ) : (
              filteredReports.map((item, index) => (
                <tr key={item._id || index}>
                  <td>{item.id || index + 1}</td>

                  <td>
                    <strong>{item.reportId}</strong>
                  </td>

                  <td>{item.reportType}</td>

                  <td>{item.fundCategory}</td>

                  <td>{item.exportFormat}</td>

                  <td>{item.generatedBy}</td>

                  <td>{item.generatedDate}</td>

                  <td>
                    <button
                      type="button"
                      onClick={() => handleExportReport(item._id)}
                      style={{
                        display: "inline-flex",
                        alignItems: "center",
                        gap: "6px",
                        background: "#f3f4f6",
                        border: "1px solid #d1d5db",
                        padding: "6px 12px",
                        borderRadius: "6px",
                        cursor: "pointer",
                        color: "#dc2626",
                        fontWeight: "600",
                      }}
                    >
                      <FileText size={14} />
                      Export
                    </button>
                  </td>
                </tr>
              ))
            )}
          </DataTable>
        </div>
      </div>

      {/* Modal Wrapper for Form */}
      <ModalWrapper 
        isOpen={isModalOpen} 
        onClose={() => setIsModalOpen(false)} 
        title="Generate New Report"
      >
        <AddClassForm fields={ReportsFormSchema} onSubmit={handleAddReport} />
      </ModalWrapper>
    </div>
  );
};

export default Reportss2;